"""
Rewrite the citations in work/shelters-for-all.ipynb to JDH official format.

JDH official inline format (Chicago Author-Date):
    (<cite data-cite="LIBRARY_ID/ITEM_KEY"></cite>)
    (<cite data-cite="LIB/K1"></cite>; <cite data-cite="LIB/K2"></cite>)
    (<cite data-cite="LIB/K"></cite>, 22)
    As shown by <cite data-cite="LIB/K"></cite>

The visible "(Author Year)" text is rendered by the JDH Jupyter viewer
(jupyterlab-citation-manager) at view time from data-cite alone.

Bibliography is generated by Better BibTeX's item.bibliography JSON-RPC with
the chicago-author-date CSL style and contentType=html, then wrapped with
<i id="zotero|GROUP/KEY"></i> anchors at the start of each csl-entry.

Library: MELICA, web group ID 5390891, local id 7.
"""

